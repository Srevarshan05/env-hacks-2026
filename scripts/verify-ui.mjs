async function noOverflow(page, label) {
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `${label}: horizontal overflow`)
  const broken = await page.locator('img').evaluateAll(images => images.filter(image => image.loading !== 'lazy' && (!image.complete || !image.naturalWidth)).map(image => image.src))
  assert.deepEqual(broken, [], `${label}: broken images`)
}

